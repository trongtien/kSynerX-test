CREATE TYPE product_last_source_enum AS ENUM ('POLLING', 'WEBHOOK', 'EXCEL');
CREATE TYPE source_type_enum AS ENUM ('WEBHOOK', 'EXCEL', 'POLLING');

CREATE TABLE products (
  sku                VARCHAR(100) PRIMARY KEY,
  product_id         INTEGER,
  partner_sku        VARCHAR(100),
  product_name       VARCHAR(255) NOT NULL,
  asset_type         VARCHAR(30),
  color              VARCHAR(100),
  size               VARCHAR(100),
  description        TEXT,
  has_serial         BOOLEAN      NOT NULL DEFAULT FALSE,
  has_expiration     BOOLEAN      NOT NULL DEFAULT FALSE,
  is_active          BOOLEAN      NOT NULL DEFAULT TRUE,
  units              JSONB        NOT NULL DEFAULT '[]',
  categories         JSONB        NOT NULL DEFAULT '[]',
  checksum_hash      CHAR(64)     NOT NULL,
  source_updated_at  TIMESTAMPTZ  NOT NULL,
  last_source        product_last_source_enum NOT NULL,
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_products_partner_sku ON products (partner_sku);
CREATE INDEX idx_products_updated_at  ON products (updated_at);


CREATE TABLE ingestion_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type source_type_enum NOT NULL,
    status VARCHAR(30) NOT NULL,
    total_records INTEGER DEFAULT 0 NOT NULL,
    created_count INTEGER DEFAULT 0 NOT NULL,
    updated_count INTEGER DEFAULT 0 NOT NULL,
    skipped_count INTEGER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_ingestion_logs_created_at ON ingestion_logs(created_at);

CREATE TYPE audit_log_change_type_enum AS ENUM ('CREATED', 'UPDATED');
CREATE TABLE product_audit_log (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                VARCHAR(100) NOT NULL REFERENCES products (sku) ON DELETE RESTRICT,
    change_type        audit_log_change_type_enum NOT NULL,
    source_type        source_type_enum NOT NULL,
    ingestion_id       BIGINT       REFERENCES ingestion_logs (id),
    event_key          VARCHAR(255),
    checksum_hash      CHAR(64)     NOT NULL,
    details            JSONB,
    source_updated_at  TIMESTAMPTZ  NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_sku_created_at ON product_audit_log (sku, created_at);
CREATE INDEX idx_audit_ingestion_id   ON product_audit_log (ingestion_id);
CREATE UNIQUE INDEX uq_audit_one_created_per_sku ON product_audit_log (sku) WHERE change_type = 'CREATED';


